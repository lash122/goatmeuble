-- ---------- CATEGORIES ----------
create table if not exists categories (
  id bigint generated by default as identity primary key,
  name_fr text not null,
  name_ar text not null,
  name_en text not null,
  sort int not null default 0,
  created_at timestamptz not null default now()
);

-- ---------- PRODUCTS ----------
create table if not exists products (
  id bigint generated by default as identity primary key,
  name_fr text not null,
  name_ar text not null,
  name_en text not null,
  description_fr text default '',
  description_ar text default '',
  description_en text default '',
  price numeric not null check (price >= 0),
  compare_at_price numeric check (compare_at_price >= 0),
  photos text[] not null default '{}',
  sizes text[] not null default '{"S","M","L","XL","XXL"}',
  category_id bigint references categories(id) on delete set null,
  stock int not null default 0 check (stock >= 0),
  featured boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------- ORDERS (cash on delivery only) ----------
create table if not exists orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  address text not null,
  zone text not null,                -- delivery zone (wilaya / area)
  delivery_fee numeric not null default 0,
  items jsonb not null,              -- [{product_id, name_*, size, price, qty, photo}]
  subtotal numeric not null,
  total numeric not null,
  status text not null default 'new' -- new | confirmed | shipped | delivered | cancelled
        check (status in ('new','confirmed','shipped','delivered','cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on orders (created_at desc);
create index if not exists orders_phone_idx on orders (phone, created_at desc);

-- ---------- SETTINGS (store name, phone, delivery zones) ----------
create table if not exists settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
