-- Visitors: read the catalogue, and nothing else.
create policy "read categories" on categories
  for select using (true);

-- hidden products stay hidden even for someone calling the API by hand
create policy "read active products" on products
  for select using (active = true);

-- only the storefront-facing settings are public: shop identity, delivery
-- zones, the active global sale and the free-delivery threshold
create policy "read public settings" on settings
  for select using (key in ('store', 'zones', 'promo', 'free_delivery_from'));

-- Orders: no public read, no public write. Visitors go through place_order().
create policy "owner only orders" on orders
  for all using (public.is_owner()) with check (public.is_owner());

-- The owner — and only the owner — manages the rest.
create policy "owner writes categories" on categories
  for all using (public.is_owner()) with check (public.is_owner());
create policy "owner writes products" on products
  for all using (public.is_owner()) with check (public.is_owner());
create policy "owner writes settings" on settings
  for all using (public.is_owner()) with check (public.is_owner());
create policy "owner writes promo codes" on promo_codes
  for all using (public.is_owner()) with check (public.is_owner());


