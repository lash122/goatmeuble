-- remove the policies from earlier versions of this file
drop policy if exists "public read categories" on categories;
drop policy if exists "public read products"   on products;
drop policy if exists "public read settings"   on settings;
drop policy if exists "public place orders"    on orders;
drop policy if exists "owner all categories"   on categories;
drop policy if exists "owner all products"     on products;
drop policy if exists "owner all orders"       on orders;
drop policy if exists "owner all settings"     on settings;

drop policy if exists "read categories"        on categories;
drop policy if exists "owner writes categories" on categories;
drop policy if exists "read active products"   on products;
drop policy if exists "owner writes products"  on products;
drop policy if exists "read public settings"   on settings;
drop policy if exists "owner writes settings"  on settings;
drop policy if exists "owner only orders"      on orders;

-- Visitors: read the catalogue, and nothing else.
create policy "read categories" on categories
  for select using (true);

-- hidden products stay hidden even for someone calling the API by hand
create policy "read active products" on products
  for select using (active = true);

-- only the store name/phone and the delivery zones are public
create policy "read public settings" on settings
  for select using (key in ('store', 'zones'));

-- Orders: no public read, no public write. Visitors go through place_order().
create policy "owner only orders" on orders
  for all using (public.is_owner()) with check (public.is_owner());

-- The owner — and only the owner — manages the rest.
create policy "owner writes categories" on categories
  for all using (public.is_owner()) with check (public.is_owner());
create policy "owner writes products" on products
  for all using (public.is_owner()) with check (public.is_owner());
create policy "owner writes settings" on settings
  for all using (public.is_owner()) with check (public.is_owner());


