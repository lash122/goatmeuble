-- ---------- PROMO CODES (v1.1) ----------
-- Not readable by the public: customers only learn a code's discount by
-- entering it, and place_order() re-validates it anyway. Codes like
-- BIENVENUE10 give a percentage off; min_order is optional.
create table if not exists promo_codes (
  id bigint generated by default as identity primary key,
  code text not null unique,
  percent int not null check (percent between 1 and 90),
  min_order numeric not null default 0 check (min_order >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

